/*
  Publish the 2026 summer/fall gatherings members expect in Recent events,
  and store audience as GPs, LPs, or GPs & LPs.
*/

UPDATE public.capital_events
SET
  audience = CASE
    WHEN audience ~* '\yLP\y' AND audience !~* '\yGP\y' AND audience !~* 'general partner' THEN 'LPs'
    WHEN (audience ~* '\yGP\y' OR audience ~* 'general partner' OR audience ~* 'emerging manager')
      AND audience !~* '\yLP\y' AND audience !~* 'allocator' THEN 'GPs'
    WHEN audience ~* 'allocator' AND audience !~* '\yGP\y' THEN 'LPs'
    ELSE 'GPs & LPs'
  END,
  updated_at = timezone('utc', now())
WHERE audience IS DISTINCT FROM 'GPs'
  AND audience IS DISTINCT FROM 'LPs'
  AND audience IS DISTINCT FROM 'GPs & LPs';

