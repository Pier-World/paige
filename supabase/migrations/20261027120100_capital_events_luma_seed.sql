UPDATE public.capital_events
SET
  status = 'cancelled',
  published_at = NULL,
  updated_at = timezone('utc', now())
WHERE slug IN (
  'super-secret-tech-conference-nov-2026',
  'collective-poker-series-nov-2026',
  'collective-poker-invitational-dec-2026'
);

UPDATE public.capital_events
SET
  status = 'completed',
  updated_at = timezone('utc', now())
WHERE status = 'upcoming'
  AND starts_at < timezone('utc', now())
  AND luma_event_id IS NULL;

UPDATE public.capital_events
SET
  published_at = NULL,
  updated_at = timezone('utc', now())
WHERE luma_event_id IS NULL
  AND starts_at < timezone('utc', now()) - interval '90 days';

